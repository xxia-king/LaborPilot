_NEGATION_PREFIXES = (
    "不涉及", "不属于", "不是", "并非", "没有发生", "未发生", "不存在", "并无",
    "无需处理", "不主张", "排除", "没有被", "未被", "没有", "没", "无",
)
_NEGATION_SUFFIXES = ("无关", "不在本案范围", "不属于本案", "无需处理")
_OUT_OF_DOMAIN_MARKERS = ("与劳动关系无关", "不是劳动争议", "不属于劳动争议", "非劳动争议")


def _trigger_is_negated(text, start, trigger):
    """判断命中词是否处在明确排除语境，不把“未签／未缴”等事实本身当成排除。"""
    prefix = text[max(0, start - 10):start]
    suffix = text[start + len(trigger):start + len(trigger) + 10]
    return any(prefix.endswith(marker) for marker in _NEGATION_PREFIXES) or any(
        suffix.startswith(marker) for marker in _NEGATION_SUFFIXES
    )


def _has_active_trigger(text, trigger):
    start = text.find(trigger)
    while start >= 0:
        if not _trigger_is_negated(text, start, trigger):
            return True
        start = text.find(trigger, start + 1)
    return False


def _explicitly_out_of_domain(text):
    normalized = re.sub(r"\s+", "", text)
    return any(marker in normalized for marker in _OUT_OF_DOMAIN_MARKERS)


def _detected_intents(text):
    """识别常见劳动争议意图，用于补足字面切片难以覆盖的核心争点。"""
    normalized = re.sub(r"\s+", "", text)
    return [
        profile
        for profile in _INTENT_PROFILES
        if any(_has_active_trigger(normalized, trigger) for trigger in profile["triggers"])
    ]


def _internal_id_pattern(cards):
    """生成仅用于过滤内部卡号的模式，不将卡号暴露到查询结果。"""
    card_ids = sorted(
        {str(card.get("id", "")).strip() for card in cards if card.get("id")},
        key=len,
        reverse=True,
    )
    if not card_ids:
        return None
    alternatives = "|".join(re.escape(card_id) for card_id in card_ids)
    return re.compile(rf"(?<![A-Za-z0-9])(?:{alternatives})(?![A-Za-z0-9])")


def _sanitize_text(text, internal_id_pattern, max_chars):
    """清理内部卡号与原始 Markdown 标记，并限制单个字段的输出长度。"""
    cleaned = str(text or "")
    if internal_id_pattern:
        cleaned = internal_id_pattern.sub("", cleaned)
    cleaned = re.sub(r"(?m)^#{1,6}\s*", "", cleaned)
    cleaned = re.sub(r"[ \t]+(?=\n)", "", cleaned)
    cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned).strip()
    if len(cleaned) > max_chars:
        cleaned = cleaned[:max_chars].rstrip() + "…"
    return cleaned


def _excerpt(body, keywords, internal_id_pattern, max_chars=700, max_chunks=4):
    chunks = [part.strip() for part in body.split("\n") if part.strip()]
    ranked = []
    for index, chunk in enumerate(chunks):
        score = sum(len(keyword) ** 2 for keyword in keywords if keyword in chunk)
        if score:
            ranked.append((-score, index, chunk))
    selected = [item[2] for item in sorted(ranked)[:max_chunks]]
    if not selected:
        selected = chunks[:max_chunks]
    return _sanitize_text("\n".join(selected), internal_id_pattern, max_chars)


def _field_match_score(content, keywords):
    return sum(len(keyword) ** 2 for keyword in keywords if keyword in content)


def query_knowledge(text):
    """在脚本内部查询编译知识，按相关性返回任务型片段。"""
    if not isinstance(text, str) or not text.strip():
        return []
    if _explicitly_out_of_domain(text):
        return []
    if not _COMPILED_KNOWLEDGE:
        print("ERROR 脚本未包含编译知识载荷，请恢复完整的 LaborPilot 发布包。", file=sys.stderr)
        sys.exit(1)

    cards = marshal.loads(zlib.decompress(base64.b64decode(_COMPILED_KNOWLEDGE)))
    detected_intents = _detected_intents(text)
    fragments = re.findall(r"[\u4e00-\u9fff]{2,}|[A-Za-z0-9§]+", text)
    keywords = []
    for fragment in fragments:
        if len(fragment) <= 8:
            keywords.append(fragment)
        if re.fullmatch(r"[\u4e00-\u9fff]+", fragment):
            for size in (2, 3, 4):
                keywords.extend(
                    fragment[index:index + size]
                    for index in range(len(fragment) - size + 1)
                )
    for profile in detected_intents:
        keywords.extend(profile["expansions"])
    keywords = list(dict.fromkeys(keywords))
    if not keywords:
        return []

    internal_id_pattern = _internal_id_pattern(cards)
    scored = []
    for card in cards:
        # 案由门只用于内部组织知识，不作为查询结果返回。
        if not card.get("g"):
            continue
        title = str(card.get("t", ""))
        gate = str(card.get("g", ""))
        body = str(card.get("bd", ""))
        zhejiang = str(card.get("zj", ""))
        score = (
            _field_match_score(title, keywords) * 8
            + _field_match_score(gate, keywords) * 3
            + min(_field_match_score(body, keywords), 100)
            + min(_field_match_score(zhejiang, keywords), 50)
        )
        if score:
            scored.append((score, card))
    scored.sort(key=lambda item: -item[0])

    results = []
    if not scored:
        return results
    minimum_score = scored[0][0] * 0.75
    matched_cards = [item for item in scored if item[0] >= minimum_score]
    if detected_intents:
        intent_title_terms = {
            term
            for profile in detected_intents
            for term in (*profile["expansions"], *profile["core_issue_terms"])
        }
        matched_cards = [
            item
            for item in matched_cards
            if any(term in str(item[1].get("t", "")) for term in intent_title_terms)
        ]
    matched_objects = {id(card) for _, card in matched_cards}
    for profile in detected_intents:
        for card in cards:
            if not card.get("g") or id(card) in matched_objects:
                continue
            title = str(card.get("t", ""))
            if any(term in title for term in profile["core_issue_terms"]):
                matched_cards.append((0, card))
                matched_objects.add(id(card))
    for _, card in matched_cards:
        results.append({
            "issue": _sanitize_text(card.get("t", ""), internal_id_pattern, 120),
            "analysis_points": _excerpt(
                card.get("bd", ""),
                keywords,
                internal_id_pattern,
                max_chars=700,
                max_chunks=4,
            ),
            "zhejiang_guidance": _excerpt(
                card.get("zj", ""),
                keywords,
                internal_id_pattern,
                max_chars=280,
                max_chunks=2,
            ),
        })
    return results


def format_result(result, index):
    lines = []
    lines.append(f"{index}. 争点：{result.get('issue', '')}")
    points = result.get("analysis_points", "")
    if points:
        lines.append("分析要点：")
        lines.append(points)
    guidance = result.get("zhejiang_guidance", "")
    if guidance:
        lines.append("浙江口径：")
        lines.append(guidance)

    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="LaborPilot issue router")
    ap.add_argument("--search", required=True, help="具体案件问题或争点描述")
    args = ap.parse_args()

    results = query_knowledge(args.search)
    if not results:
        print("未匹配到相关内置争点，应结合案件材料另行分析并核验法律依据。")
        sys.exit(1)
    print(f"案件分析内部匹配结果（{len(results)} 项）：")
    for index, result in enumerate(results, 1):
        print(format_result(result, index))
        if index != len(results):
            print()


if __name__ == "__main__":
    main()
